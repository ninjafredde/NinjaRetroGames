#!/usr/bin/env python3
"""art/music.txt -> src/gen/music.asm (the tune as bytes, instruments, note frequencies).

Stream bytes per voice: note (0 = rest, 1-96) + length in frames; $FE n = instrument n; $FF = loop.
Note numbers match the C64 player: octave * 12 + semitone + 1, so a4 = 58 = 440 Hz.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEMI = {"c": 0, "d": 2, "e": 4, "f": 5, "g": 7, "a": 9, "b": 11}
DUTY = {"12": 0, "25": 1, "50": 2, "75": 3}
ARP = {"none": 0, "major": 1, "minor": 2}


class MusicError(Exception):
    pass


def note_number(tok, where):
    name = tok.lower()
    if name[:1] not in SEMI:
        raise MusicError(f"{where}: not a note: {tok}")
    semi, rest = SEMI[name[0]], name[1:]
    if rest.startswith("#"):
        semi, rest = semi + 1, rest[1:]
    if not rest.isdigit():
        raise MusicError(f"{where}: note needs an octave: {tok}")
    n = int(rest) * 12 + semi + 1
    if not 1 <= n <= 96:
        raise MusicError(f"{where}: note out of range: {tok}")
    return n


def main():
    path = ROOT / "art" / "music.txt"
    tempo = 7
    instruments = {}
    voices = {}
    cur = None
    for num, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        where = f"music.txt:{num}"
        line = raw.split(";", 1)[0].strip()
        if not line:
            continue
        words = line.split()
        if words[0] == "tempo":
            tempo = int(words[1])
        elif words[0] == "instrument":
            inst = {"duty": 2, "volume": 10, "fade": 0, "arp": 0, "wobble": 0, "pluck": 0}
            for w in words[2:]:
                k, _, v = w.partition("=")
                if k == "duty":
                    inst["duty"] = DUTY[v]
                elif k in ("volume", "fade"):
                    inst[k] = int(v)
                elif k == "arp":
                    inst["arp"] = ARP[v]
                elif k in ("wobble", "pluck"):
                    inst[k] = 1
                else:
                    raise MusicError(f"{where}: unknown instrument setting {w}")
            instruments[int(words[1])] = inst
        elif words[0] == "@voice":
            cur = int(words[1])
            if cur not in (1, 2, 3):
                raise MusicError(f"{where}: voices are 1, 2 (pulse) and 3 (wave)")
            voices[cur] = []
        else:
            if cur is None:
                raise MusicError(f"{where}: notes before any @voice")
            out = voices[cur]
            for tok in words:
                if tok == "|":
                    continue
                if tok.startswith("@"):
                    out += [0xFE, int(tok[1:])]
                    continue
                name, _, length = tok.partition(":")
                rows = int(length) if length else 1
                frames = rows * tempo
                if not 1 <= frames <= 255:
                    raise MusicError(f"{where}: {tok} is too long ({frames} frames, max 255)")
                note = 0 if name.lower() == "r" else note_number(name, where)
                out += [note, frames]
    for v in (1, 2, 3):
        if v not in voices:
            raise MusicError(f"music.txt: no @voice {v}")
    if sorted(instruments) != list(range(len(instruments))):
        raise MusicError("music.txt: instruments must be numbered 0, 1, 2 ...")

    out = ["; Generated by tools/music.py from art/music.txt - edit the text, not this file", "",
           'SECTION "Music data", ROM0', "InstTab:  ; duty, envelope, arp, wobble, pluck"]
    for i in range(len(instruments)):
        it = instruments[i]
        env = (it["volume"] << 4) | it["fade"]
        out.append(f"    db ${it['duty'] << 6:02X}, ${env:02X}, {it['arp']}, {it['wobble']}, {it['pluck']}")
    out += ["ArpTab:", "    db 0,0,0, 0,4,7, 0,3,7", "DutySeq:", "    db $40, $80, $C0, $80",
            "WaveTriangle:",
            "    db $01,$23,$45,$67,$89,$AB,$CD,$EF,$FE,$DC,$BA,$98,$76,$54,$32,$10"]
    for label, clock in (("PulseFreq", 131072), ("WaveFreq", 65536)):
        vals = [0]
        for n in range(1, 97):
            f = 440 * 2 ** ((n - 58) / 12)
            vals.append(max(0, min(2047, round(2048 - clock / f))))
        out.append(f"{label}:")
        for i in range(0, 97, 12):
            out.append("    dw " + ",".join(str(v) for v in vals[i:i + 12]))
    out.append("SongVoices:")
    out.append("    dw Voice1, Voice2, Voice3")
    for v in (1, 2, 3):
        data = voices[v] + [0xFF]
        out.append(f"Voice{v}:")
        for i in range(0, len(data), 16):
            out.append("    db " + ",".join(f"${b:02X}" for b in data[i:i + 16]))
    out.append("")
    gen = ROOT / "src" / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "music.asm").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"music: {len(instruments)} instruments, " +
          ", ".join(f"voice {v} {len(voices[v])} bytes" for v in (1, 2, 3)))


if __name__ == "__main__":
    try:
        main()
    except (MusicError, KeyError, ValueError) as e:
        print("music error:", e, file=sys.stderr)
        sys.exit(1)
